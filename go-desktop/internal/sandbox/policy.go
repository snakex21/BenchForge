// Package sandbox ports electron/toolRuntime.cjs (python.run, node.run, file
// tools, SVG path tool, MCP passthrough) with a stricter execution policy:
//
//   - Model-generated code runs in Docker by default (--network none,
//     --cap-drop ALL, no-new-privileges, pids/memory/CPU limits, read-only
//     root filesystem, unprivileged user, container removed on timeout).
//   - Running it directly on the host requires an explicit opt-in that the
//     user confirms in a warning dialog (preference "sandbox_host_optin").
//     Without Docker and without that opt-in, code execution is refused.
//   - The executable, interpreter path and Docker image can no longer be
//     chosen by the model (the Electron build accepted pythonPath/nodePath/
//     useDocker/pythonImage from tool-call input).
package sandbox

import "github.com/snakex21/benchforge/go-desktop/internal/jsv"

// Preference keys.
const (
	PrefUseDocker = "sandbox_use_docker" // existing Electron key; unset => Docker (new default)
	PrefHostOptIn = "sandbox_host_optin" // new; true only after the warning dialog
)

// Default images (pinned tags, not chosen by the model).
const (
	PythonImage = "python:3.12-alpine"
	NodeImage   = "node:22-alpine"
)

// Mode is the effective execution mode.
type Mode string

const (
	ModeDocker  Mode = "docker"
	ModeHost    Mode = "host"
	ModeRefused Mode = "refused"
)

// Policy decides where model-generated code may run.
type Policy struct {
	UseDocker bool // Docker is the configured backend
	HostOptIn bool // user explicitly accepted host execution
}

// PolicyFromPrefs builds the policy from stored preferences. A missing
// sandbox_use_docker means Docker (secure default); an explicit false from the
// Electron era is NOT treated as consent to run code on the host.
func PolicyFromPrefs(useDocker any, hostOptIn any) Policy {
	p := Policy{UseDocker: true}
	if b, ok := useDocker.(bool); ok && !b {
		p.UseDocker = false
	}
	if b, ok := hostOptIn.(bool); ok && b {
		p.HostOptIn = true
	}
	return p
}

// Mode returns where code runs.
func (p Policy) Mode() Mode {
	if p.UseDocker {
		return ModeDocker
	}
	if p.HostOptIn {
		return ModeHost
	}
	return ModeRefused
}

// HostWarning is shown before the user enables host execution.
const HostWarning = "Disabling the Docker sandbox makes BenchForge run code generated by AI models DIRECTLY ON THIS COMPUTER, " +
	"with your user account's permissions. Network blocking on the host is best-effort only and the code can read, change or delete your files.\n\n" +
	"Only continue if you trust every model and benchmark you run.\n\nRun model-generated code on the host?"

// RefusedMessage explains why code was not executed.
const RefusedMessage = "Code execution refused: the Docker sandbox is disabled and running model-generated code on the host has not been explicitly enabled. " +
	"Enable the Docker sandbox in Settings (recommended) or turn it off and confirm the host-execution warning."

// Describe is used by the health check.
func (p Policy) Describe() jsv.Obj {
	return jsv.Obj{"mode": string(p.Mode()), "useDocker": p.UseDocker, "hostOptIn": p.HostOptIn}
}
